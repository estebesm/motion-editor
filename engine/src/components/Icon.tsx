export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];
export const isIcon = (n?: string): n is IconName => !!n && n in ICONS;

export const Icon: React.FC<{name?: string; size: number; color: string; stroke?: number; style?: React.CSSProperties}> = ({
  name,
  size,
  color,
  stroke = 2,
  style,
}) => {
  if (!isIcon(name)) return null;
  const C = ICONS[name];
  return <C size={size} color={color} strokeWidth={stroke} style={style} />;
};
